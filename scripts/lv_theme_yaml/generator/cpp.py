"""Small helpers to write C++ text."""

from __future__ import annotations

from pathlib import Path


def banner(inputs: list[Path]) -> str:
    names = ", ".join(path.name for path in inputs)
    return f"// Generated by lv_theme_yaml from {names} — do not edit\n"


def header_file(inputs: list[Path], guard: str, body: str) -> str:
    return f"{banner(inputs)}#ifndef {guard}\n#define {guard}\n\n{body}\n#endif //{guard}\n"


def local(header: str) -> str:
    return f'"{header}"'


def system(header: str) -> str:
    return f"<{header}>"


def include_groups(*groups: list[str]) -> str:
    """One block of #include per group, each block followed by a blank line."""
    return "".join(
        "".join(f"#include {header}\n" for header in group) + "\n"
        for group in groups
        if group
    )


def std_array(name: str, element_type: str, items: list[str]) -> str:
    """constexpr std::array with deduced type, or an explicit empty one."""
    if not items:
        return f"constexpr std::array<{element_type}, 0> {name}{{}};\n"
    body = "".join(f"    {item},\n" for item in items)
    return f"constexpr std::array {name}{{\n{body}}};\n"


def to_array(name: str, element_type: str, items: list[str]) -> str:
    """std::to_array for elements written as braced lists."""
    body = "".join(f"    {item},\n" for item in items)
    return f"constexpr auto {name} = std::to_array<{element_type}>({{\n{body}}});\n"


def enum_class(name: str, members: list[str]) -> str:
    values = ", ".join([*members, "COUNT"])
    return f"enum class {name} {{ {values} }};\n"


def count_assert(array: str, enum: str) -> str:
    return f"static_assert({array}.size() == static_cast<size_t>({enum}::COUNT));\n"
